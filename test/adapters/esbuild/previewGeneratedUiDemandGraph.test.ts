/** Generated UI demand stays lazy on normal graphs and survives reached star-barrel cycles. */
import { createRequire } from 'node:module';
import { mkdir, mkdtemp, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { build } from 'esbuild';
import { describe, expect, it, vi } from 'vitest';
import { createPreviewGeneratedUiFallbackPlugin } from '../../../src/adapters/esbuild/previewGeneratedUiFallbackPlugin';
import { createPreviewStaticModuleResolver } from '../../../src/adapters/esbuild/previewStaticModuleResolver';

const requireModule = createRequire(import.meta.url);

describe('lazy generated UI export demand', () => {
  it('does not read importer source for an entirely resolved relative graph', async () => {
    const root = await realpath(await mkdtemp(path.join(tmpdir(), 'generated-ui-resolved-')));
    try {
      const entry = path.join(root, 'entry.ts');
      await Promise.all([
        writeFile(
          entry,
          "import { first } from './first'; import { second } from './second'; export const result = [first, second];",
        ),
        writeFile(path.join(root, 'first.ts'), 'export const first = 1;'),
        writeFile(path.join(root, 'second.ts'), 'export const second = 2;'),
      ]);
      const readSource = vi.fn<(file: string) => string | undefined>();
      const result = await build({
        absWorkingDir: root,
        bundle: true,
        entryPoints: [entry],
        format: 'cjs',
        logLevel: 'silent',
        plugins: [
          createPreviewGeneratedUiFallbackPlugin({
            readSource,
            staticModuleResolver: createPreviewStaticModuleResolver({ workspaceRoot: root }),
            workspaceRoot: root,
          }),
        ],
        write: false,
      });
      expect(execute(result.outputFiles[0]?.text ?? '')).toMatchObject({ result: [1, 2] });
      expect(readSource).not.toHaveBeenCalled();
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });

  it.each([false, true])(
    'recovers a generated export through multiple star barrels (cycle: %s)',
    async (cycle) => {
      const root = await realpath(await mkdtemp(path.join(tmpdir(), 'generated-ui-star-graph-')));
      try {
        await mkdir(path.join(root, 'styles'));
        const entry = path.join(root, 'entry.ts');
        await Promise.all([
          writeFile(
            path.join(root, 'tsconfig.json'),
            JSON.stringify({ compilerOptions: { baseUrl: '.', paths: { '@/*': ['./*'] } } }),
          ),
          writeFile(
            path.join(root, 'styles', 'README.md'),
            'This UI tree is autogenerated by the registry build process and gitignored.',
          ),
          writeFile(entry, "import { Button } from './first'; export const ButtonType = Button;"),
          writeFile(path.join(root, 'first.ts'), "export * from './second';"),
          writeFile(
            path.join(root, 'second.ts'),
            [cycle ? "export * from './first';" : '', "export * from '@/styles/ui/controls';"].join(
              '\n',
            ),
          ),
        ]);
        const result = await build({
          absWorkingDir: root,
          bundle: true,
          entryPoints: [entry],
          external: ['react'],
          format: 'cjs',
          logLevel: 'silent',
          plugins: [
            createPreviewGeneratedUiFallbackPlugin({
              staticModuleResolver: createPreviewStaticModuleResolver({ workspaceRoot: root }),
              workspaceRoot: root,
            }),
          ],
          write: false,
        });
        const exports = execute(result.outputFiles[0]?.text ?? '') as {
          readonly ButtonType?: { readonly displayName?: string };
        };
        expect(typeof exports.ButtonType).toBe('function');
        expect(exports.ButtonType?.displayName).toBe('PreviewGenerated(Button)');
        expect(result.warnings).toHaveLength(1);
      } finally {
        await rm(root, { recursive: true, force: true });
      }
    },
  );
});

/** Executes only this test's synthetic module; React is the already installed fixed dependency. */
function execute(contents: string): unknown {
  const module = { exports: {} };
  vm.runInNewContext(contents, { module, exports: module.exports, require: requireModule });
  return module.exports;
}
