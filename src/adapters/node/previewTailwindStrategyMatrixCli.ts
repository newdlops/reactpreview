/**
 * Command-line entry for the Tailwind strategy matrix and seed generator.
 *
 * Usage (through `scripts/pretrain-tailwind-strategies.mjs`):
 * `--installs <dir>` holds one npm prefix per release (`<dir>/<version>/node_modules`),
 * `--report <file>` receives the full JSON matrix, and `--write-seed <file>` regenerates the
 * read-only seed module shipped with the extension.
 */
import { existsSync, readdirSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  createPreviewAdapterStrategySeed,
  runPreviewTailwindStrategyMatrix,
  type PreviewTailwindMatrixRow,
} from './previewTailwindStrategyMatrix';

/**
 * Runs the matrix for every completed install and writes the requested outputs.
 *
 * @param argv Command-line arguments after the script path.
 * @returns Process exit code: 0 when every release compiled the fixture completely.
 */
export async function runPreviewTailwindStrategyMatrixCli(
  argv: readonly string[],
): Promise<number> {
  const readOption = (name: string): string | undefined => {
    const index = argv.indexOf(name);
    return index < 0 ? undefined : argv[index + 1];
  };
  const installsRoot = path.resolve(
    readOption('--installs') ?? '.tmp/tailwind-strategy-matrix/installs',
  );
  const reportPath = path.resolve(
    readOption('--report') ?? '.tmp/tailwind-strategy-matrix/report.json',
  );
  const seedPath = readOption('--write-seed');
  const installs = readdirSync(installsRoot)
    .filter((version) => existsSync(path.join(installsRoot, version, '.done')))
    .sort(compareVersions)
    .map((version) => ({
      nodeModulesPath: path.join(installsRoot, version, 'node_modules'),
      version,
    }));
  const rows = await runPreviewTailwindStrategyMatrix(
    installs,
    path.join(path.dirname(reportPath), 'fixtures'),
  );
  await writeFile(reportPath, `${JSON.stringify(rows, undefined, 2)}\n`, 'utf8');
  for (const row of rows) process.stdout.write(`${describeRow(row)}\n`);
  if (seedPath !== undefined) {
    await writeFile(path.resolve(seedPath), createSeedModule(rows), 'utf8');
    process.stdout.write(`seed written to ${seedPath}\n`);
  }
  return rows.every(
    (row) =>
      Object.values(row.pipeline.checks).every(Boolean) &&
      Object.values(row.boundedPipeline.checks).every(Boolean),
  )
    ? 0
    : 1;
}

/** Formats one matrix row as a single report line. */
function describeRow(row: PreviewTailwindMatrixRow): string {
  const strategies = row.measurements
    .map(
      (measurement) =>
        `${measurement.strategy}=${measurement.passed ? 'pass' : 'fail'}(${String(measurement.durationMs)}ms)`,
    )
    .join(' ');
  const failedChecks = Object.entries(row.pipeline.checks)
    .filter(([, passed]) => !passed)
    .map(([name]) => name);
  const pipeline =
    row.pipeline.error === undefined
      ? failedChecks.length === 0
        ? 'pipeline=ok'
        : `pipeline=missing:${failedChecks.join(',')}`
      : `pipeline=error:${row.pipeline.error.slice(0, 80)}`;
  const boundedFailed = Object.entries(row.boundedPipeline.checks)
    .filter(([, passed]) => !passed)
    .map(([name]) => name);
  const bounded =
    row.boundedPipeline.error === undefined
      ? boundedFailed.length === 0
        ? 'bounded=ok'
        : `bounded=missing:${boundedFailed.join(',')}`
      : `bounded=error:${row.boundedPipeline.error.slice(0, 80)}`;
  return `${row.version.padEnd(8)} rule=${row.ruleStrategy ?? 'none'} ${strategies} ${pipeline} ${bounded}`;
}

/** Renders the seed as a small typed data module. */
function createSeedModule(rows: readonly PreviewTailwindMatrixRow[]): string {
  const seed = createPreviewAdapterStrategySeed(rows);
  const versions = rows.map((row) => row.version);
  const outcomeLines = Object.entries(seed.outcomes)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(
      ([key, outcome]) =>
        `    ${JSON.stringify(key)}: { at: 0, passed: ${String(outcome.passed)} },`,
    );
  const headLines = Object.entries(seed.heads).map(
    ([key, head]) =>
      `    ${JSON.stringify(key)}: { bias: ${round(head.bias)}, updates: ${String(head.updates)}, weights: [${head.weights.map(round).join(', ')}] },`,
  );
  return [
    '/**',
    ' * Read-only adapter-strategy seed measured offline against real Tailwind releases.',
    ' *',
    ` * Generated by \`node scripts/pretrain-tailwind-strategies.mjs --write-seed\` from ${String(versions.length)} releases`,
    ` * (${versions[0] ?? ''}–${versions.at(-1) ?? ''}). Do not edit by hand; rerun the script after new releases.`,
    ' * Only passes and machine-independent failures are seeded, so a fresh install skips self-tests',
    ' * for known releases while every machine-specific problem is still measured locally.',
    ' */',
    "import type { PreviewAdapterStrategyDocument } from './previewAdapterStrategyLearner';",
    '',
    '/** Exact strategy outcomes and pre-trained heads for the Tailwind compile strategies. */',
    'export const PREVIEW_ADAPTER_STRATEGY_SEED: PreviewAdapterStrategyDocument = {',
    '  heads: {',
    ...headLines,
    '  },',
    '  outcomes: {',
    ...outcomeLines,
    '  },',
    `  schema: ${String(seed.schema)},`,
    '};',
    '',
  ].join('\n');
}

/** Rounds a weight for a stable, readable seed. */
function round(value: number): string {
  return String(Math.round(value * 10_000) / 10_000);
}

/** Orders semantic versions numerically. */
function compareVersions(left: string, right: string): number {
  const leftParts = left.split('.').map(Number);
  const rightParts = right.split('.').map(Number);
  for (let index = 0; index < 3; index += 1) {
    const difference = (leftParts[index] ?? 0) - (rightParts[index] ?? 0);
    if (difference !== 0) return difference;
  }
  return 0;
}
