/** Missing generated aliases must not mask authored sources selected by TypeScript path priority. */
import { mkdir, mkdtemp, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { build } from 'esbuild';
import { afterEach, describe, expect, it, vi } from 'vitest';
import * as pathIdentity from '../../../src/shared/pathIdentity';
import { createPreviewGeneratedUiFallbackPlugin } from '../../../src/adapters/esbuild/previewGeneratedUiFallbackPlugin';
import { createPreviewStaticModuleResolver } from '../../../src/adapters/esbuild/previewStaticModuleResolver';

const roots: string[] = [];
afterEach(async () => {
  vi.restoreAllMocks();
  await Promise.all(roots.splice(0).map((root) => rm(root, { force: true, recursive: true })));
});

describe('generated UI alias priority', () => {
  it('preserves an existing later target instead of replacing it with an earlier generated placeholder', async () => {
    const { root, entry } = await fixture({ '@ui/*': ['generated/*', 'authored/*'] });
    await mkdir(path.join(root, 'authored'));
    await writeFile(path.join(root, 'authored', 'button.ts'), 'export const Button = "authored";');
    const resolver = createPreviewStaticModuleResolver({ workspaceRoot: root });
    const result = await build({
      absWorkingDir: root,
      entryPoints: [entry],
      bundle: true,
      write: false,
      format: 'cjs',
      logLevel: 'silent',
      plugins: [
        createPreviewGeneratedUiFallbackPlugin({
          workspaceRoot: root,
          staticModuleResolver: resolver,
        }),
      ],
    });
    const module = { exports: {} as { Button?: unknown } };
    vm.runInNewContext(result.outputFiles[0]?.text ?? '', { module, exports: module.exports });
    expect(module.exports.Button).toBe('authored');
    expect(result.warnings).toHaveLength(0);
    expect(resolver.resolveMissingPathAliasCandidate('@ui/button', entry)).toBeUndefined();
  });

  it('rejects ordinary existing aliases before walking real ancestors and observes newly created source', async () => {
    const { root, entry } = await fixture({ '@ui/*': ['generated/*'] });
    const resolver = createPreviewStaticModuleResolver({ workspaceRoot: root });
    expect(resolver.resolveMissingPathAliasCandidate('@ui/button', entry)).toBe(
      path.join(root, 'generated', 'button'),
    );
    await writeFile(path.join(root, 'generated', 'button.ts'), 'export const Button = "fresh";');
    const canonicalize = vi.spyOn(pathIdentity, 'canonicalizePathThroughExistingAncestor');
    expect(resolver.resolveMissingPathAliasCandidate('@ui/button', entry)).toBeUndefined();
    expect(canonicalize).not.toHaveBeenCalled();
  });

  it('does not select a broader mapping after the best mapping resolves to authored source', async () => {
    const { root, entry } = await fixture({
      '@ui/button': ['authored/button'],
      '@ui/*': ['generated/*'],
    });
    await mkdir(path.join(root, 'authored'));
    await writeFile(path.join(root, 'authored', 'button.ts'), 'export const Button = "specific";');
    const resolver = createPreviewStaticModuleResolver({ workspaceRoot: root });
    expect(resolver.resolveMissingPathAliasCandidate('@ui/button', entry)).toBeUndefined();
  });

  it('leaves an alias package directory to ordinary package-main resolution', async () => {
    const { root, entry } = await fixture({ '@ui/*': ['generated/*'] });
    const packageRoot = path.join(root, 'generated', 'button');
    await mkdir(packageRoot);
    await writeFile(path.join(packageRoot, 'package.json'), '{"main":"authored.js"}');
    await writeFile(path.join(packageRoot, 'authored.js'), 'export const Button = "package";');
    const resolver = createPreviewStaticModuleResolver({ workspaceRoot: root });
    expect(resolver.resolveMissingPathAliasCandidate('@ui/button', entry)).toBeUndefined();
  });
});

/** Owns a tiny inert alias fixture, with explicit generation evidence beside missing candidates. */
async function fixture(paths: Record<string, string[]>): Promise<{ root: string; entry: string }> {
  const root = await realpath(await mkdtemp(path.join(tmpdir(), 'react-preview-alias-priority-')));
  roots.push(root);
  await mkdir(path.join(root, 'generated'));
  const entry = path.join(root, 'Page.ts');
  await Promise.all([
    writeFile(
      path.join(root, 'tsconfig.json'),
      JSON.stringify({ compilerOptions: { baseUrl: '.', paths } }),
    ),
    writeFile(
      path.join(root, 'generated', 'README.md'),
      'This UI tree is autogenerated by the build process.',
    ),
    writeFile(entry, 'export { Button } from "@ui/button";'),
  ]);
  return { root, entry };
}
