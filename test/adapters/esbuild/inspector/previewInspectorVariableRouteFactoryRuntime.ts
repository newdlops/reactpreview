/** Bundles only controlled factories and the real Router, then renders generated roots in memory. */
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { runInNewContext } from 'node:vm';
import { build } from 'esbuild';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import type { PreviewInspectorPageCandidate } from '../../../../src/adapters/esbuild/inspector/previewInspectorAncestorTypes';
import { createPreviewInspectorRootSource } from '../../../../src/adapters/esbuild/inspector/previewInspectorRootSource';
import { createPreviewInspectorPageCandidateRuntimeSource } from '../../../../src/adapters/esbuild/pageInspector/previewInspectorPageCandidateRuntimeSource';
import { createPreviewInspectorCorridorPlugin } from '../../../../src/adapters/esbuild/inspector/previewInspectorCorridorPlugin';
import { createPreviewCompilerFrontierPolicy } from '../../../../src/domain/previewCompilerFrontier';
import { preparePreviewInspectorBundleFrontier } from '../../../../src/adapters/esbuild/inspector/previewInspectorBundleFrontier';
import { createPreviewInspectorPageExecutionCandidates } from '../../../../src/adapters/esbuild/inspector/previewInspectorPageExecutionCandidates';
import { createPreviewInspectorPageExecutionSource } from '../../../../src/adapters/esbuild/inspector/previewInspectorPageExecutionSource';
import { createPreviewInspectorExecutionRootModuleContract } from '../../../../src/adapters/esbuild/inspector/previewInspectorExecutionRootModuleContract';
import { PREVIEW_INSPECTOR_PAGE_EXECUTION_SPECIFIER } from '../../../../src/adapters/esbuild/inspector/previewInspectorPageExecutionEntryPlugin';
import type { VariableRouteFactoryFixture } from './previewInspectorVariableRouteFactoryFixture';
import type { PreviewInspectorRouteBranch } from '../../../../src/adapters/esbuild/inspector/previewInspectorRouteBranchPlan';
import type { PreviewInspectorPageExecutionCandidate } from '../../../../src/adapters/esbuild/inspector/previewInspectorPageExecutionTypes';

/** Explicit route/compiler variants; every source is generated by the controlled fixture writer. */
export interface VariableRouteFactoryCase {
  /** Stable generated candidate identity for this independently built scenario. */
  readonly name: string;
  /** Public compiler-offered selection; absent to follow the ordinary authored primary root. */
  readonly selection?: 'ListPage' | 'CreatePage' | 'ManagementApp';
  /** Exact page marker expected after the real Router matches the candidate's initial entry. */
  readonly marker: string;
  /** Uses the frozen execution/frontier production path instead of the legacy virtual wrapper. */
  readonly frozen?: boolean;
  /** Removes runtime metadata to exercise only the compiler-proven fallback prefix. */
  readonly omitRuntimeBase?: boolean;
  /** Changes the exact mount owner identity to prove unauthorized localization is rejected. */
  readonly wrongOwner?: boolean;
  /** Adds an accessor that must never execute or be copied by the static metadata allowlist. */
  readonly getterStatic?: boolean;
  /** Prepends an earlier exact-owner mount to exercise last-owner compiler localization. */
  readonly repeatedOwner?: boolean;
}

type FixtureComponent = React.ComponentType & {
  basePath?: string;
  allPages?: unknown;
  pageNames?: unknown;
  virtualPageRecipe?: unknown;
  unlistedProbeStatic?: string;
};
type RuntimeCandidate = Pick<
  PreviewInspectorPageCandidate,
  'id' | 'routeLocation' | 'routeMountBasePath'
>;

/** Narrow contracts of controlled generated exports, not an alternate Router implementation. */
interface GeneratedEntry {
  /** Serialized browser metadata emitted by the real compiler. */
  readonly default: readonly { inspector: { pageCandidates: readonly RuntimeCandidate[] } }[];
  /** Actual compiled root loaders. */
  readonly probeCandidates: readonly { id: string; load: () => Promise<FixtureComponent> }[];
  /** Production pathname localization function under test. */
  readonly probeInitialEntry: (
    candidate: RuntimeCandidate,
    root: FixtureComponent,
    direct: boolean,
  ) => string;
  /** Authored root used to compare static references without invoking metadata accessors. */
  readonly probeOriginalRoot: () => Promise<FixtureComponent>;
  /** Real package component bundled with the fixture's Routes/Route/useParams. */
  readonly MemoryRouter: React.ComponentType<{
    initialEntries: string[];
    children: React.ReactNode;
  }>;
}

/** Compiles and renders one controlled selection; output code never becomes a disk artifact. */
export async function renderVariableRouteFactoryCase(
  fixture: VariableRouteFactoryFixture,
  variant: VariableRouteFactoryCase,
): Promise<VariableRouteFactoryObservation> {
  const { appPath, root, readSource, resolveModule, reference, renderPath, renderChain } = fixture;
  const branch = await fixture.collect(
    variant.selection === undefined ? undefined : fixture.select(variant.selection),
  );
  if (variant.selection !== undefined) assert.equal(branch.selectionResolution, 'exact');
  const activeLocation = branch.activeLocation ?? branch.primary;
  assert.ok(activeLocation);
  let location =
    variant.wrongOwner && activeLocation.routeMounts !== undefined
      ? {
          ...activeLocation,
          routeMounts: activeLocation.routeMounts.map((mount) => ({
            ...mount,
            exportName: 'DifferentExport',
          })),
        }
      : activeLocation;
  if (variant.repeatedOwner) {
    const exactOwner = location.routeMounts?.find(
      (mount) => mount.sourcePath === appPath && mount.exportName === reference.exportName,
    );
    assert.ok(exactOwner, 'The repeated-owner case requires a compiler-proven owner');
    location = {
      ...location,
      routeMounts: Object.freeze([
        Object.freeze({
          ...exactOwner,
          basePath: '/unrelated-outer-mount',
          routeSlotCount: 99,
          hasWildcardFallback: false,
        }),
        ...(location.routeMounts ?? []),
      ]),
    };
  }
  const candidate = {
    id: variant.name,
    root: reference,
    target: reference,
    complete: true,
    dependencyPaths: [
      ...branch.dependencyPaths,
      appPath,
      ...(location.sourcePath ? [location.sourcePath] : []),
    ],
    edges: [],
    rootAutomaticProps: {},
    targetAutomaticProps: {},
    rootOwnsRouter: false,
    rootStepIndex: 0,
    renderPath,
    routeLocation: location,
    stopReason: 'root-reached' as const,
  };
  const plan = {
    ...candidate,
    renderChain,
    renderChainsByExport: { FeatureApp: renderChain },
    pageCandidates: [candidate],
    routeBranches: branch.branches,
    ...(branch.selectedBranchId === undefined
      ? {}
      : { selectedRouteBranchId: branch.selectedBranchId }),
  };
  const execution = variant.frozen
    ? createPreviewInspectorPageExecutionCandidates({ plan })[0]
    : undefined;
  if (variant.frozen) assert.ok(execution, 'Missing source-backed frozen execution candidate');
  const policy = createPreviewCompilerFrontierPolicy('fast');
  assert.ok(policy);
  const prepared = execution
    ? await preparePreviewInspectorBundleFrontier({
        executionCandidate: execution,
        plan,
        policy,
        readSource,
        resolveModule,
        workspaceRoot: root,
      })
    : undefined;
  if (prepared) assert.equal(prepared.rejected, false);
  const executionSource = execution
    ? createPreviewInspectorPageExecutionSource({
        candidate: execution,
        executionRootModuleContract: createPreviewInspectorExecutionRootModuleContract({
          ...execution.executionRootContract,
          preparedSourceText:
            fixture.sourceByPath.get(execution.executionRootContract.sourcePath) ?? '',
        }),
        target: execution.runtimeTargetContract,
      })
    : undefined;
  const source = [
    createPreviewInspectorRootSource({
      plan,
      ...(execution ? { pageExecutionCandidate: execution } : {}),
    }),
    createPreviewInspectorPageCandidateRuntimeSource(),
    'export const probeCandidates = __reactPreviewInspectorCandidates;',
    'export const probeInitialEntry = createPreviewInspectorCandidateInitialEntry;',
    `export async function probeOriginalRoot() { return (await import(${JSON.stringify(appPath)})).FeatureApp; }`,
    "export { MemoryRouter } from 'react-router-dom';",
    ...(variant.getterStatic
      ? [
          `import { FeatureApp as FixtureApp } from ${JSON.stringify(appPath)};`,
          "globalThis.probeGetterReads = 0; Object.defineProperty(FixtureApp, 'basePath', { configurable: true, get() { globalThis.probeGetterReads++; throw new Error('Unexpected getter read'); } });",
        ]
      : []),
  ].join('\n');
  const requireLocal = createRequire(import.meta.url);
  const built = await build({
    stdin: { contents: source, resolveDir: root, sourcefile: 'variable-route-factory-runtime.mjs' },
    absWorkingDir: root,
    bundle: true,
    format: 'cjs',
    platform: 'node',
    write: false,
    jsx: 'automatic',
    minifyWhitespace: true,
    legalComments: 'none',
    external: ['react', 'react-dom', 'react/jsx-runtime', 'react/jsx-dev-runtime'],
    plugins: [
      {
        name: 'controlled-exports-and-real-router',
        setup(builder) {
          builder.onResolve({ filter: /^react-router-dom$/ }, () => ({
            path: requireLocal.resolve('react-router-dom'),
          }));
          builder.onResolve({ filter: /^react-preview:inspector-page-execution$/ }, (args) => {
            assert.equal(args.path, PREVIEW_INSPECTOR_PAGE_EXECUTION_SPECIFIER);
            return { path: 'execution', namespace: 'controlled-execution' };
          });
          builder.onLoad({ filter: /.*/, namespace: 'controlled-execution' }, () => {
            assert.ok(executionSource);
            return { contents: executionSource, loader: 'js', resolveDir: root };
          });
          builder.onResolve({ filter: /^react-preview:inspector-target-facade$/ }, () => ({
            path: appPath,
          }));
          builder.onResolve({ filter: /^react-preview:inspector-direct-target\// }, () => ({
            path: 'direct',
            namespace: 'controlled-direct',
          }));
          builder.onLoad({ filter: /.*/, namespace: 'controlled-direct' }, () => ({
            contents: `export { FeatureApp as default } from ${JSON.stringify(appPath)};`,
            loader: 'js',
            resolveDir: root,
          }));
        },
      },
      createPreviewInspectorCorridorPlugin({
        plan,
        projectRoot: root,
        workspaceRoot: root,
        resolveModule,
        ...(prepared
          ? {
              frozenAuthenticSourcePaths: prepared.frontier.authenticSourcePaths,
              authenticComponentExports: prepared.frontier.authenticComponentExports,
              projectedEdges: prepared.frontier.projectedEdges,
            }
          : {}),
      }),
    ],
  });
  const output = built.outputFiles[0]?.text;
  assert.ok(output);
  const module = { exports: {} as GeneratedEntry };
  const warnings: string[] = [];
  const context = {
    module,
    exports: module.exports,
    require: requireLocal,
    setTimeout,
    clearTimeout,
    process,
    URL,
    AbortController,
    TextEncoder,
    TextDecoder,
    probeGetterReads: 0,
    console: {
      log(...args: unknown[]) {
        warnings.push(args.join(' '));
      },
      warn(...args: unknown[]) {
        warnings.push(args.join(' '));
      },
      error(...args: unknown[]) {
        warnings.push(args.join(' '));
      },
    },
  };
  runInNewContext(output, context);
  const entry = module.exports;
  const browserCandidate = entry.default[0]?.inspector.pageCandidates.find(
    (value) => value.id === candidate.id,
  );
  assert.ok(browserCandidate);
  assert.ok(browserCandidate.routeLocation);
  const Original = await entry.probeOriginalRoot();
  Original.unlistedProbeStatic = 'DO_NOT_COPY';
  const loader = entry.probeCandidates.find((value) => value.id === candidate.id);
  assert.ok(loader);
  const Root = await loader.load();
  const copiedBase = Object.getOwnPropertyDescriptor(Root, 'basePath');
  if (variant.omitRuntimeBase)
    Object.defineProperty(Root, 'basePath', { configurable: true, value: undefined });
  const initialEntry = entry.probeInitialEntry(browserCandidate, Root, false);
  const html = renderToStaticMarkup(
    variant.frozen
      ? React.createElement(Root)
      : React.createElement(entry.MemoryRouter, {
          initialEntries: [initialEntry],
          children: React.createElement(Root),
        }),
  );
  const fallbackEntry = entry.probeInitialEntry(
    {
      ...browserCandidate,
      routeLocation: { ...browserCandidate.routeLocation, pathname: '/feature/unmatched' },
    },
    Root,
    false,
  );
  const fallbackHtml = variant.frozen
    ? undefined
    : renderToStaticMarkup(
        React.createElement(entry.MemoryRouter, {
          initialEntries: [fallbackEntry],
          children: React.createElement(Root),
        }),
      );
  return {
    html,
    fallbackHtml,
    initialEntry,
    routeCount: branch.branches.length,
    branches: branch.branches,
    getterReads: context.probeGetterReads,
    copiedBase,
    siblingMarkers: [
      'SIBLING_MODULE_MARKER',
      'SIBLING_SETTINGS_MODULE_MARKER',
      'SIBLING_AUDIT_MODULE_MARKER',
    ].filter((marker) => output.includes(marker)),
    bundledPageMarkers: ['LIST_PAGE_MARKER', 'CREATE_PAGE_MARKER', 'NOT_FOUND_MARKER'].filter(
      (marker) => output.includes(marker),
    ),
    statics: {
      allPagesReferencePreserved: Root.allPages === Original.allPages,
      pageNamesReferencePreserved: Root.pageNames === Original.pageNames,
      unlistedPropertyExcluded: !Object.hasOwn(Root, 'unlistedProbeStatic'),
      displayNamePreserved: Root.displayName?.startsWith('PagePreview(') === true,
      recipePreserved: Root.virtualPageRecipe !== undefined,
    },
    runtimeStaticEntry: entry.probeInitialEntry(
      { ...browserCandidate, routeMountBasePath: '/different-base' },
      Root,
      false,
    ),
    frozenFidelity: execution?.fidelity,
    warnings,
  };
}

/** Observable production behavior and static contracts retained without persisting generated code. */
export interface VariableRouteFactoryObservation {
  /** Actual selected-route React SSR output. */
  readonly html: string;
  /** Authored wildcard output for unmatched legacy-router locations. */
  readonly fallbackHtml: string | undefined;
  /** Production-selected Router entry. */
  readonly initialEntry: string;
  /** Inert route inventory count after selection. */
  readonly routeCount: number;
  /** Original public branch identities used for rebuild comparisons. */
  readonly branches: readonly PreviewInspectorRouteBranch[];
  /** Must remain zero even when metadata is an accessor. */
  readonly getterReads: number;
  /** Static descriptor actually copied by the generated wrapper. */
  readonly copiedBase: PropertyDescriptor | undefined;
  /** Disallowed unselected module markers found in the generated bundle. */
  readonly siblingMarkers: readonly string[];
  /** Controlled authored page markers retained in the emitted in-memory JavaScript bundle. */
  readonly bundledPageMarkers: readonly string[];
  /** Independent safe-static reference, name, and allowlist checks. */
  readonly statics: Readonly<Record<string, boolean>>;
  /** Entry when deliberately conflicting compiler metadata is supplied. */
  readonly runtimeStaticEntry: string;
  /** Compiler fidelity for the frozen execution path. */
  readonly frozenFidelity: PreviewInspectorPageExecutionCandidate['fidelity'] | undefined;
  /** Captured controlled-render diagnostics. */
  readonly warnings: readonly string[];
}
